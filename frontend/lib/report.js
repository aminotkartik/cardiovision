export const SAFETY_DISCLAIMER = 'EDUCATIONAL / DECISION-SUPPORT PROTOTYPE — Predictions are generated by machine-learning models and are not a diagnosis. They must not replace professional clinical assessment, ECG or imaging interpretation, coronary angiography, or other appropriate medical evaluation. These outputs are not validated for clinical decision-making.';

export function buildReport({ sessionId, features, prediction, explanation, demoMode, schema, health }) {
  return {
    report_type: 'CardioVision 3D model-generated research prototype output',
    analysis_id: sessionId,
    created_at: new Date().toISOString(),
    synthetic_demo: Boolean(demoMode),
    real_inference_completed: Boolean(prediction),
    input_values: features || {},
    input_measurements: (schema?.fields || []).map((field) => ({
      name: field.name,
      label: field.label || field.name,
      group: field.group,
      unit: field.unit || null,
      value: features?.[field.name] ?? null,
      missing: features?.[field.name] === null || features?.[field.name] === undefined || features?.[field.name] === '',
    })),
    predictions: prediction || null,
    selected_target_explanation: explanation || null,
    model_schema: schema?.feature_names || [],
    model_readiness_at_export: health?.inference_available ? 'available' : 'unavailable',
    warnings: prediction?.warnings || [],
    limitations: [
      'Predictions are uncalibrated model scores from a small source cohort and have not been independently clinically validated.',
      'The three vessel classifiers and overall CAD classifier are separate models; scores may not be mutually consistent.',
      'Feature attribution is approximate and non-causal; it does not establish biological cause or anatomical lesion location.',
      'The 3D heart and coronary paths are stylized procedural illustrations, not patient-specific anatomy or imaging.',
      'Synthetic demonstration data are not an observed person and have no ground-truth labels.',
    ],
    disclaimer: SAFETY_DISCLAIMER,
  };
}
