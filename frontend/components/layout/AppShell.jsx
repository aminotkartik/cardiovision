'use client';

import {
  Activity, BookOpen, BrainCircuit, FileText, HeartPulse, LayoutDashboard,
  Plus, Stethoscope, Waypoints,
} from 'lucide-react';

const NAVIGATION = [
  { id: 'overview', label: 'Overview', icon: LayoutDashboard },
  { id: 'analysis', label: 'Patient analysis', icon: Stethoscope },
  { id: 'anatomy', label: '3D anatomy explorer', icon: HeartPulse },
  { id: 'performance', label: 'Model performance', icon: BrainCircuit },
  { id: 'reports', label: 'Reports & docs', icon: FileText },
];

export const VIEW_META = {
  overview: { eyebrow: 'Workbench · 01', title: 'Cardiovascular signal explorer', description: 'See the signals. Explore the anatomy. Understand the model output.' },
  analysis: { eyebrow: 'Patient analysis · 02', title: 'Clinical feature review', description: 'Enter the features present in the inspected dataset, validate the record, then request the four independent model outputs.' },
  anatomy: { eyebrow: 'Anatomy explorer · 03', title: 'Coronary vessel model scores', description: 'An interactive, stylized procedural heart illustrates model-predicted scores — it is not patient-specific imaging or a stenosis map.' },
  performance: { eyebrow: 'Model evaluation · 04', title: 'Evaluation & methodology', description: 'Review saved test-set results, training-only model selection, class balance, and the leakage audit.' },
  reports: { eyebrow: 'Analysis exports · 05', title: 'Report & project notes', description: 'Export a model-generated research summary or review provenance, reproducibility, limitations, and safety.' },
};

export default function AppShell({ activeView, setActiveView, sessionId, health, onNewAnalysis, children }) {
  const ready = health?.inference_available === true;
  const statusClass = !health ? 'pending' : ready ? 'ready' : 'failed';
  const statusText = !health ? 'Checking API' : ready ? 'Models loaded' : 'Setup required';

  return (
    <div className="app-shell">
      <aside className="sidebar" aria-label="Primary navigation">
        <div className="brand">
          <div className="brand-mark" aria-hidden="true"><HeartPulse size={18} strokeWidth={1.8} /></div>
          <div className="brand-copy">
            <div className="brand-title">CARDIOVISION</div>
            <div className="brand-subtitle">3D · research workbench</div>
          </div>
        </div>
        <div className="nav-label">Workspace</div>
        <nav className="nav-list">
          {NAVIGATION.map(({ id, label, icon: Icon }) => (
            <button
              type="button"
              key={id}
              className={`nav-item ${activeView === id ? 'active' : ''}`}
              onClick={() => setActiveView(id)}
              aria-current={activeView === id ? 'page' : undefined}
              title={label}
            >
              <Icon size={16} strokeWidth={1.8} aria-hidden="true" />
              <span>{label}</span>
            </button>
          ))}
        </nav>
        <div className="sidebar-bottom">
          <div className="sidebar-prototype">
            <strong><Waypoints size={13} /> Prototype scope</strong>
            <p>Four separate tabular classifiers. No patient-specific scan, angiographic image, or plaque segmentation is used.</p>
          </div>
          <div className="sidebar-footer">
            Educational / decision-support prototype. Outputs are not a diagnosis and are not validated for clinical decision-making.
          </div>
        </div>
      </aside>

      <div className="workspace">
        <header className="topbar">
          <div className="topbar-left">
            <div className="session-label"><Activity size={14} aria-hidden="true" /> <span>Analysis</span> <span className="session-id">{sessionId}</span></div>
            <div className={`status-pill ${statusClass}`} title={health?.missing_artifacts?.join(', ') || statusText}>
              <i className="status-dot" aria-hidden="true" />
              <span>{statusText}</span>
            </div>
          </div>
          <div className="topbar-right">
            <span className="educational-badge"><BookOpen size={11} style={{ verticalAlign: '-2px', marginRight: 4 }} />Educational prototype</span>
            <button type="button" className="btn btn-primary btn-small" onClick={onNewAnalysis}>
              <Plus size={14} /> New analysis
            </button>
          </div>
        </header>

        <main className="main-content">{children}</main>
        <div className="global-safety" role="note" aria-label="Medical safety disclaimer">
          <span className="global-safety-marker" aria-hidden="true" />
          <span><strong>EDUCATIONAL / DECISION-SUPPORT PROTOTYPE</strong> — Predictions are generated by machine-learning models and are not a diagnosis. They must not replace professional clinical assessment, ECG or imaging interpretation, coronary angiography, or other appropriate medical evaluation. These outputs are not validated for clinical decision-making.</span>
        </div>
      </div>
    </div>
  );
}
