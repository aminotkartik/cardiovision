"""Inspect a local source dataset and save a schema before training."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from app.ml.data import build_feature_columns, load_dataset, resolve_targets, summarize_dataset
from app.ml.schema import infer_feature_schema, leakage_audit_columns


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", required=True, help="Local CSV/XLSX file; no data are uploaded.")
    parser.add_argument("--output-dir", default=str(ROOT / "artifacts"))
    parser.add_argument("--cad-target", default=None, help="Overall target column; auto-selects CAD, then Cath.")
    parser.add_argument("--lad-target", default="LAD")
    parser.add_argument("--lcx-target", default="LCX")
    parser.add_argument("--rca-target", default="RCA")
    args = parser.parse_args()

    frame = load_dataset(args.data)
    targets = resolve_targets(list(frame.columns), {
        "cad": args.cad_target, "lad": args.lad_target, "lcx": args.lcx_target, "rca": args.rca_target,
    })
    features = build_feature_columns(list(frame.columns), targets)
    audit = leakage_audit_columns(features)
    if not audit["passed"]:
        raise SystemExit(f"Leakage audit failed: {audit}")
    schema = infer_feature_schema(frame, features)
    schema["feature_names"] = features
    schema["target_names"] = targets
    schema["schema_version"] = 1
    schema["source"] = "Generated by audit_dataset.py from the explicitly supplied local dataset."
    summary = summarize_dataset(frame, features, targets)
    summary["leakage_audit"] = audit

    output = Path(args.output_dir)
    output.mkdir(parents=True, exist_ok=True)
    (output / "schema.json").write_text(json.dumps(schema, indent=2), encoding="utf-8")
    (output / "dataset_audit.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    print(json.dumps(summary, indent=2))
    print(f"\nSchema and audit saved in {output}")


if __name__ == "__main__":
    main()
